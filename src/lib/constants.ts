// Helper to filter cards by bank or keywords with smart aliases
export const getCardsForBank = (bankNameOrCode: string): BankCardCatalogItem[] => {
  if (!bankNameOrCode) return BANK_CREDIT_CARDS_CATALOG;
  const lower = bankNameOrCode.toLowerCase().trim();

  // Keyword aliases map
  const aliases: Record<string, string[]> = {
    hdfc: ['hdfc', 'hdfc bank', 'tata neu', 'millennia', 'infinia', 'regalia'],
    sbi: ['sbi', 'state bank of india', 'sbi card', 'simplyclick', 'simplysave', 'aurum'],
    icici: ['icici', 'icici bank', 'amazon pay', 'coral', 'sapphiro', 'emeralde', 'adani one'],
    axis: ['axis', 'axis bank', 'airtel', 'flipkart', 'magnus', 'atlas', 'ace', 'kiwi', 'neo', 'privilege'],
    kotak: ['kotak', 'kotak mahindra', 'kotak mahindra bank', '811', 'white', 'league'],
    idfc: ['idfc', 'idfc first', 'idfc first bank', 'swyp', 'ashva', 'mayura', 'wealth', 'select'],
    federal: ['federal', 'federal bank', 'scapia', 'celesta', 'signet', 'fi-federal'],
    indusind: ['indusind', 'indusind bank', 'legend', 'tiger', 'nexxt'],
    rbl: ['rbl', 'rbl bank', 'world safari', 'shoprite', 'play', 'insignia', 'binge'],
    yes: ['yes', 'yes bank', 'marquee', 'reserv'],
    bob: ['bob', 'bank of baroda', 'baroda', 'eterna', 'energie'],
    pnb: ['pnb', 'punjab national bank', 'punjab national', 'wave'],
    canara: ['canara', 'canara bank'],
    union: ['union', 'union bank', 'union bank of india', 'uni carbon'],
    au: ['au', 'au bank', 'au small finance', 'au small finance bank', 'zenith', 'ixigo', 'lit'],
    sc: ['sc', 'standard chartered', 'stan chart', 'ultimate', 'digismart'],
    hsbc: ['hsbc', 'hsbc bank', 'hsbc india', 'live+'],
    amex: ['amex', 'american express', 'mrcc', 'smart earn'],
    onecard: ['onecard', 'one card'],
  };

  const results = BANK_CREDIT_CARDS_CATALOG.filter(card => {
    const issuerLower = card.issuer.toLowerCase();
    const nameLower = card.name.toLowerCase();

    if (issuerLower.includes(lower) || lower.includes(issuerLower) || nameLower.includes(lower) || lower.includes(nameLower)) {
      return true;
    }

    // Check alias matching
    for (const [, aliasList] of Object.entries(aliases)) {
      const inputMatches = aliasList.some(a => lower.includes(a) || a.includes(lower));
      const cardMatches = aliasList.some(a => issuerLower.includes(a) || nameLower.includes(a));
      if (inputMatches && cardMatches) return true;
    }

    return false;
  });

  // If no direct bank match found, return the full catalog
  return results.length > 0 ? results : BANK_CREDIT_CARDS_CATALOG;
};

// Helper to get bank theme config
export const getBankTheme = (themeIdOrBankName: string) => {
  if (!themeIdOrBankName) return BANK_ACCOUNT_THEMES[0];
  const found = BANK_ACCOUNT_THEMES.find(
    t =>
      t.id === themeIdOrBankName ||
      t.bankCode.toLowerCase() === themeIdOrBankName.toLowerCase() ||
      t.name.toLowerCase().includes(themeIdOrBankName.toLowerCase())
  );
  return found || BANK_ACCOUNT_THEMES[0];
};

